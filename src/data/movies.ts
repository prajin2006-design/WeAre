/**
 * Generates a gradient-based placeholder poster URL.
 * Uses picsum.photos for realistic placeholder imagery.
 * Each seed produces a deterministic, unique image.
 */
function poster(seed: string): string {
  return `https://picsum.photos/seed/${seed}/400/600`;
}

function backdrop(seed: string): string {
  return `https://picsum.photos/seed/${seed}/1920/1080`;
}

